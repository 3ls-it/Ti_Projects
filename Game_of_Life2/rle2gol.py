#!/usr/bin/env python3
"""
Convert Conway's Game of Life RLE files to TIGCC C header files.

The generated coordinates are centered in a 159x99 world by default.

Example call:
./rle2gol.py gosper-glider-gun.rle \
    --output include/gosper_glider_gun.h \
    --name gosper_glider_gun
"""

import argparse
import re
import sys
from pathlib import Path


HEADER_RE = re.compile(
    r"x\s*=\s*(\d+)\s*,\s*y\s*=\s*(\d+)"
    r"(?:\s*,\s*rule\s*=\s*([^,\s]+))?",
    re.IGNORECASE,
)


def sanitize_identifier(value):
    """Convert a filename-like name into a valid C identifier."""
    value = re.sub(r"[^A-Za-z0-9_]", "_", value)
    value = re.sub(r"_+", "_", value).strip("_")

    if not value:
        value = "pattern"

    if value[0].isdigit():
        value = "_" + value

    return value.lower()


def parse_rle(path):
    """Return (declared_width, declared_height, rule, live_cells)."""
    header = None
    data_lines = []

    with path.open("r", encoding="ascii") as source:
        for raw_line in source:
            line = raw_line.strip()

            if not line:
                continue

            if line.startswith("#"):
                continue

            if header is None:
                match = HEADER_RE.search(line)

                if match:
                    header = match
                    continue

            data_lines.append(line)

    if header is None:
        raise ValueError("RLE header not found")

    width = int(header.group(1))
    height = int(header.group(2))
    rule = header.group(3) or "B3/S23"

    data = "".join(data_lines)
    live_cells = []

    x = 0
    y = 0
    number = ""

    for char in data:
        if char.isdigit():
            number += char
            continue

        if char in ("b", "o", "$", "!"):
            run = int(number) if number else 1
            number = ""

            if char == "b":
                x += run

            elif char == "o":
                for offset in range(run):
                    live_cells.append((x + offset, y))
                x += run

            elif char == "$":
                y += run
                x = 0

            elif char == "!":
                break

        elif char.isspace():
            continue

        else:
            raise ValueError(f"unexpected RLE character: {char!r}")

    return width, height, rule, live_cells


def make_include_guard(identifier):
    return "GOL_PATTERN_{}_H".format(identifier.upper())


def emit_header(
    output_path,
    identifier,
    width,
    height,
    rule,
    live_cells,
    world_width,
    world_height,
):
    if width > world_width or height > world_height:
        raise ValueError(
            f"pattern ({width}x{height}) does not fit "
            f"world ({world_width}x{world_height})"
        )

    origin_x = (world_width - width) // 2
    origin_y = (world_height - height) // 2

    guard = make_include_guard(identifier)
    count_macro = "{}_COUNT".format(identifier.upper())
    width_macro = "{}_WIDTH".format(identifier.upper())
    height_macro = "{}_HEIGHT".format(identifier.upper())
    origin_x_macro = "{}_ORIGIN_X".format(identifier.upper())
    origin_y_macro = "{}_ORIGIN_Y".format(identifier.upper())
    rule_macro = "{}_RULE".format(identifier.upper())

    lines = [
        "/*",
        " * Generated by rle2gol.py.",
        f" * Source pattern: {identifier}",
        f" * RLE dimensions: {width} x {height}",
        f" * Rule: {rule}",
        f" * Centered in: {world_width} x {world_height}",
        " */",
        "",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        '#include "gol_types.h"',
        "",
        f"#define {width_macro} {width}",
        f"#define {height_macro} {height}",
        f"#define {origin_x_macro} {origin_x}",
        f"#define {origin_y_macro} {origin_y}",
        f'#define {rule_macro} "{rule}"',
        "",
        f"static const Cell {identifier}[] = {{",
    ]

    for x, y in live_cells:
        lines.append(f"    {{ {origin_x + x}, {origin_y + y} }},")

    lines.extend(
        [
            "};",
            "",
            f"#define {count_macro} \\",
            f"    (sizeof({identifier}) / sizeof({identifier}[0]))",
            "",
            f"#endif /* {guard} */",
            "",
        ]
    )

    output_path.write_text("\n".join(lines), encoding="ascii")


def main():
    parser = argparse.ArgumentParser(
        description="Convert Life RLE to a centered TIGCC C header."
    )
    parser.add_argument("input", type=Path, help="input .rle file")
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        help="output header; default: <input-stem>.h",
    )
    parser.add_argument(
        "-n",
        "--name",
        help="C identifier; default: derived from input filename",
    )
    parser.add_argument(
        "--world-width",
        type=int,
        default=159,
        help="world width in pixels (default: 159)",
    )
    parser.add_argument(
        "--world-height",
        type=int,
        default=99,
        help="world height in pixels (default: 99)",
    )

    args = parser.parse_args()

    identifier = sanitize_identifier(args.name or args.input.stem)
    output_path = args.output or Path(f"{identifier}.h")

    try:
        width, height, rule, live_cells = parse_rle(args.input)
        emit_header(
            output_path=output_path,
            identifier=identifier,
            width=width,
            height=height,
            rule=rule,
            live_cells=live_cells,
            world_width=args.world_width,
            world_height=args.world_height,
        )
    except (OSError, ValueError) as error:
        print(f"rle2gol.py: error: {error}", file=sys.stderr)
        return 1

    print(
        f"converted {args.input} -> {output_path} "
        f"({len(live_cells)} live cells, {width}x{height}, rule {rule})"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
